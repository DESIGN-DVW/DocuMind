#!/usr/bin/env node

/**
 * Generate docs/MARKDOWN-RULES.md from the custom rule registry.
 *
 * The registry (config/rules/index.cjs) and the rule config
 * (config/.markdownlint.json) are the source of truth; this script only
 * renders them. Run it after adding a rule or flipping an enable flag —
 * a hand-maintained rule table drifts within a week.
 *
 * Usage:
 *   node scripts/generate-rules-doc.mjs           # write the doc
 *   node scripts/generate-rules-doc.mjs --check   # exit 1 if out of date
 *
 * @module scripts/generate-rules-doc
 * @version 1.0.0
 * @created 2026-07-28
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_PATH = path.join(ROOT, 'docs/MARKDOWN-RULES.md');

const registry = require(path.join(ROOT, 'config/rules/index.cjs'));
const config = JSON.parse(await fs.readFile(path.join(ROOT, 'config/.markdownlint.json'), 'utf8'));

/** Read the first JSDoc block of a rule module for its examples. */
async function ruleDoc(name) {
  const file = path.join(ROOT, 'config/rules', `${name}.cjs`);
  const src = await fs.readFile(file, 'utf8');
  const block = src.match(/\/\*\*([\s\S]*?)\*\//);
  if (!block) return { summary: '', examples: [] };

  const body = block[1]
    .split('\n')
    .map(l => l.replace(/^\s*\*ted?\s?/, '').replace(/^\s*\*\s?/, ''))
    .join('\n');

  const examples = body
    .split('\n')
    .filter(l => /^\s*[✅❌]/.test(l))
    .map(l => l.trim());

  return { examples };
}

const rows = [];
for (const meta of registry.describeRules()) {
  const enabled = config[meta.id] !== false;
  const rule = registry.find(r => r.names.includes(meta.id));
  const fixable = String(rule.function).includes('fixInfo');
  const { examples } = await ruleDoc(meta.name);
  rows.push({ ...meta, enabled, fixable, examples });
}

rows.sort((a, b) => a.id.localeCompare(b.id));

const yes = '✅';
const no = '❌';

const lines = [
  '---',
  'title: DVW Markdown Rules',
  'description: Generated registry of DocuMind custom markdownlint rules — IDs, status, fixability, and examples.',
  'version: 1.0.0',
  `updated: ${new Date().toISOString().slice(0, 10)}`,
  'category: standards',
  'lang: en',
  '---',
  '',
  '# DVW Markdown Rules',
  '',
  '> Generated by `node scripts/generate-rules-doc.mjs` — do not edit by hand.',
  '> Source: `config/rules/` (implementations) and `config/.markdownlint.json` (status).',
  '',
  `${rows.length} custom rules. Machine IDs are \`DVWnnn\`; the human label is used in prose.`,
  '',
  '## Summary',
  '',
  '| ID | Label | Name | Status | Auto-fix |',
  '| - | - | - | - | - |',
  ...rows.map(
    r =>
      `| ${r.id} | ${r.label} | \`${r.name}\` | ${r.enabled ? `${yes} enabled` : `${no} opt-in`} | ${r.fixable ? yes : no} |`
  ),
  '',
  '## Rules',
  '',
];

for (const r of rows) {
  lines.push(`### ${r.id} — ${r.label}`, '');
  lines.push(
    `**\`${r.name}\`** · ${r.enabled ? 'enabled' : 'opt-in (disabled by default)'} · ${r.fixable ? 'auto-fixable' : 'detect only'}`,
    ''
  );
  lines.push(r.description, '');
  if (r.tags.length) lines.push(`Tags: ${r.tags.map(t => `\`${t}\``).join(', ')}`, '');
  if (r.examples.length) {
    lines.push('```text', ...r.examples, '```', '');
  }
}

lines.push(
  '## Enabling an opt-in rule',
  '',
  'The prose-rewriting rules ship disabled because pre-commit and the nightly cron both run `--fix`, so enabling one rewrites existing files unattended.',
  '',
  '1. Set the rule to `true` in `config/.markdownlint.json`',
  '2. Run `npm run lint:fix`',
  '3. Review the diff',
  '4. Commit the flag together with the changes it produced',
  '',
  '## Related',
  '',
  '- [Markdown Style Brief](./MARKDOWN-STYLE-BRIEF.md) — the policy these rules implement',
  '- `config/rules/index.cjs` — auto-discovery registry',
  '- `config/rules/_shared.cjs` — shared matchers and masking helpers',
  ''
);

const output = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = await fs.readFile(OUT_PATH, 'utf8').catch(() => null);
  if (current !== output) {
    console.error(
      'docs/MARKDOWN-RULES.md is out of date — run: node scripts/generate-rules-doc.mjs'
    );
    process.exit(1);
  }
  console.log('docs/MARKDOWN-RULES.md is up to date');
} else {
  await fs.writeFile(OUT_PATH, output, 'utf8');
  console.log(`Wrote ${path.relative(ROOT, OUT_PATH)} — ${rows.length} rules`);
}
